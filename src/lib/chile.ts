export const REGION_NAMES = REGIONS.map((r) => r.name);

export function normalize(s: string) {
  return s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().trim();
}

export function findRegion(name: string) {
  const n = normalize(name);
  return REGIONS.find((r) => normalize(r.name) === n);
}

export function isValidComuna(region: string, comuna: string) {
  const r = findRegion(region);
  if (!r) return false;
  const c = normalize(comuna);
  return r.comunas.some((x) => normalize(x) === c);
}
